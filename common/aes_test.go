func TestAES(t *testing.T) {
	s := "abc123"
	key := []byte("123456789abcdefghijklnm"[0:16])

	enc, err := AesEncrypt(nil, key)
	assert.Nil(t, err, "error:", err)
	dec, err := AesDecrypt(enc, key)
	assert.Nil(t, err, "error:", err)

	enc, err = AesEncrypt([]byte(s), key)
	assert.Nil(t, err, "error:", err)
	dec, err = AesDecrypt(enc, key)
	assert.EqualValues(t, []byte(s), dec)

	iv := []byte("1234567890123456")
	enc, err = AesEncryptWithIV([]byte(s), key, iv)
	assert.Nil(t, err, "error:", err)
	dec, err = AesDecryptWithIV(enc, key, iv)
	assert.Nil(t, err, "error:", err)
	assert.EqualValues(t, []byte(s), dec)
}

func TestAESAuthenticatedEnvelope(t *testing.T) {
	for _, size := range []int{16, 24, 32} {
		t.Run(fmt.Sprint(size), func(t *testing.T) {
			key := bytes.Repeat([]byte{7}, size)
			for _, plaintext := range [][]byte{nil, []byte("a message longer than one AES block")} {
				first, err := AesEncrypt(plaintext, key)
				require.NoError(t, err)
				second, err := AesEncrypt(plaintext, key)
				require.NoError(t, err)
				require.NotEqual(t, first, second)
				got, err := AesDecrypt(first, key)
				require.NoError(t, err)
				require.True(t, bytes.Equal(plaintext, got))
				for i := range first {
					tampered := bytes.Clone(first)
					tampered[i] ^= 1
					got, err := AesDecrypt(tampered, key)
					require.Error(t, err, "tampered byte %d", i)
					require.Nil(t, got)
				}
				for i := 0; i < len(first); i++ {
					_, err := AesDecrypt(first[:i], key)
					require.Error(t, err, "truncated length %d", i)
				}
				_, err = AesDecrypt(first, bytes.Repeat([]byte{8}, size))
				require.Error(t, err)
			}
		})
	}
	_, err := AesEncrypt(nil, []byte("bad key"))
	require.Error(t, err)
}

func TestAESLegacyMigration(t *testing.T) {
	key := []byte("0123456789abcdef")
	legacy, err := AesEncryptWithIV([]byte("stored legacy data"), key, key)
	require.NoError(t, err)
	// Golden ciphertext generated by the pre-migration implementation.
	require.Equal(t, "3d54cce25af2c9b834250ef58cd3283f05bfabe18d78f893a5a19618e9674e93", hex.EncodeToString(legacy))
	_, err = AesDecrypt(legacy, key)
	require.Error(t, err, "must not automatically accept unauthenticated ciphertext")
	plaintext, err := AesDecryptLegacy(legacy, key, nil)
	require.NoError(t, err)
	require.Equal(t, "stored legacy data", string(plaintext))
	updated, err := AesEncrypt(plaintext, key)
	require.NoError(t, err)
	got, err := AesDecrypt(updated, key)
	require.NoError(t, err)
	require.Equal(t, plaintext, got)
	_, err = AesEncryptWithIV(plaintext, key, nil)
	require.Error(t, err, "legacy encryption requires an explicit IV")
	for _, ciphertext := range [][]byte{nil, {1}, make([]byte, 15), make([]byte, 17)} {
		_, err := AesDecryptLegacy(ciphertext, key, nil)
		require.Error(t, err)
	}
}

func TestPKCSPaddingValidation(t *testing.T) {
	for _, input := range [][]byte{nil, {0}, {1, 0}, {1, 2}, {4, 4, 4}} {
		_, err := PKCS5UnPadding(input)
		require.Error(t, err)
	}
	for _, size := range []int{0, -1, 256} {
		_, err := PKCS5Padding(nil, size)
		require.Error(t, err)
	}
	for length := 0; length <= 32; length++ {
		data := bytes.Repeat([]byte{42}, length)
		padded, err := PKCS5Padding(data, 16)
		require.NoError(t, err)
		got, err := PKCS5UnPadding(padded)
		require.NoError(t, err)
		require.Equal(t, data, got)
	}
}

func FuzzAesDecrypt(f *testing.F) {
	key := []byte("0123456789abcdef")
	seed, err := AesEncrypt([]byte("seed"), key)
	if err != nil {
		f.Fatal(err)
	}
	f.Add(seed)
	f.Add([]byte(aesEnvelope))
	f.Add([]byte{})
	f.Fuzz(func(t *testing.T, data []byte) {
		plaintext, err := AesDecrypt(data, key)
		if err != nil && plaintext != nil {
			t.Fatal("plaintext returned on authentication error")
		}
		AesDecryptLegacy(data, key, nil)
	})
}
